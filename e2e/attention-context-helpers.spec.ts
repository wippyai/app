// Fixed cross-language wire bytes, not generated by the production encoder.
const COMPACT_VECTOR = '{"candidates":[{"action_ref":{"generation":1,"host_instance_id":"host-1","mount_id":"leaf-1","path_digest":"sha256:2c46a9ab38e76737a2418025f51d2c7f2f3d743bedaba84a04598fb2aed7758f","rect":{"height":24,"width":80,"x":100,"y":100},"snapshot_id":"snapshot-1","target_id":"target-1"},"occluded":false,"path_indices":[0,1],"rect":{"height":24,"width":80,"x":100,"y":100},"sample_refs":[0],"summary":{"name":"Nested status","role":"status","text":"Ready"},"target_id":"target-1"}],"capture":{"complete":true,"duration_ms":12,"grid_step_css_px":5,"points":[{"point_id":"p0","x":120,"y":112}],"radius_css_px":20,"sampled_points":1},"coordinate_space":{"device_pixel_ratio":1,"height":720,"kind":"host-viewport","width":1280},"created_at":"2026-09-04T12:00:00.000Z","host_instance_id":"host-1","mount_generation":3,"omissions":[],"path_dictionary":[{"generation":3,"kind":"host","mount_id":"host-1"},{"generation":1,"kind":"element","mount_id":"leaf-1","tag_name":"span"}],"recent_events":[],"schema":"wippy.attention.v2","snapshot_id":"snapshot-1"}'

function compactPayload() {
  return JSON.parse(COMPACT_VECTOR)
}

function oracleAttachment(payload = compactPayload(), version = 2, id = 'oracle-fixture'): ContextAttachment {
  const content = oracleCanonicalJson(payload)
  return { attachment_id: id, kind: 'wippy.attention', version, content_type: 'application/json',
    content, content_bytes: Buffer.byteLength(content), content_hash: `sha256:${createHash('sha256').update(content).digest('hex')}`,
    created_at: '2026-09-04T12:00:00.000Z' }
}

function latticePayload() {
  const payload = compactPayload()
  delete payload.capture.points
  payload.capture.point_encoding = { kind: 'css-euclidean-grid.v1', origin: { x: 120, y: 112 } }
  payload.capture.sampled_points = 49
  payload.candidates[0].sample_refs = [[0, 49]]
  return payload
}

function packedV3Payload() {
  const payload = compactPayload()
  payload.schema = 'wippy.attention.v3'
  payload.path_dictionary = payload.path_dictionary.map((segment: Record<string, unknown>) => {
    const { kind, mount_id, generation, rect, clip_rect, local_to_parent, ...attributes } = segment
    if (rect) {
      const value = rect as Record<string, number>
      attributes.rect = [value.x, value.y, value.width, value.height]
    }
    if (clip_rect) {
      const value = clip_rect as Record<string, number>
      attributes.clip_rect = [value.x, value.y, value.width, value.height]
    }
    if (local_to_parent)
      attributes.local_to_parent = (local_to_parent as { matrix: number[] }).matrix
    return [kind, mount_id, generation, attributes]
  })
  return payload
}

