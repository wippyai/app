test('independent oracle rejects corrupt envelopes and verifies mixed expansion budgets', () => {
  const valid = oracleAttachment()
  for (const changed of [
    { content_bytes: valid.content_bytes + 1 }, { content_hash: `sha256:${'0'.repeat(64)}` },
    { version: 1 }, { version: 3 }, { content_type: 'text/plain' }, { content: `${valid.content} ` },
  ])
    expect(() => attentionSnapshotFromAttachment({ ...valid, ...changed } as ContextAttachment)).toThrow()
  const payload = latticePayload()
  payload.capture.radius_css_px = 31
  payload.capture.grid_step_css_px = 1
  // Independently enumerated accepted row widths for the 31-pixel test lattice.
  let count = 0
  for (let y = -31; y <= 31; y++)
    count += 2 * Math.floor(Math.sqrt(31 * 31 - y * y)) + 1
  payload.capture.sampled_points = count
  payload.candidates[0].sample_refs = [[0, count]]
  const expanded = expandAttentionV2ForTest(payload)
  const size = Buffer.byteLength(oracleCanonicalJson(expanded))
  const permitted = Math.floor(ATTENTION_ORACLE_LIMITS.expanded / size)
  const attachments = Array.from({ length: permitted + 1 }, (_, index) => oracleAttachment(payload, 2, `compact-${index}`))
  expect(attentionSnapshotsFromAttachments(attachments.slice(0, permitted))).toHaveLength(permitted)
  expect(() => attentionSnapshotsFromAttachments(attachments)).toThrow()
  const v1 = oracleAttachment(attentionSnapshotFromAttachment(valid), 1, 'v1')
  expect(attentionSnapshotsFromAttachments([v1, valid])).toHaveLength(2)
  expect(attentionSnapshotsFromAttachments([valid, v1])).toHaveLength(2)
})

test('independent oracle checks the complete 16KiB envelope rather than only compact content', () => {
  const payload = compactPayload()
  const first = payload.candidates[0]
  payload.candidates = Array.from({ length: 32 }, (_, index) => {
    const candidate = structuredClone(first)
    candidate.target_id = `target-${index}`
    candidate.summary.text = ''
    delete candidate.action_ref
    return candidate
  })
  let attachment = oracleAttachment(payload)
  for (const candidate of payload.candidates) {
    const gap = ATTENTION_ORACLE_LIMITS.envelopeV2 - Buffer.byteLength(oracleCanonicalJson(attachment))
    if (gap <= 0)
      break
    candidate.summary.text = 'a'.repeat(Math.min(512, gap))
    attachment = oracleAttachment(payload)
  }
  expect(Buffer.byteLength(oracleCanonicalJson(attachment))).toBe(16384)
  expect(attentionSnapshotFromAttachment(attachment).candidates).toHaveLength(32)
  payload.candidates[31].summary.text += 'a'
  const excessive = oracleAttachment(payload)
  expect(Buffer.byteLength(excessive.content)).toBeLessThan(16384)
  expect(() => attentionSnapshotFromAttachment(excessive)).toThrow()
})

test('independent oracle charges mixed v1 and v2 bodies against one expansion budget in either order', () => {
  const dense = (radius: number) => {
    const value = latticePayload()
    value.capture.radius_css_px = radius
    value.capture.grid_step_css_px = 1
    let count = 0
    for (let y = -radius; y <= radius; y++)
      count += 2 * Math.floor(Math.sqrt(radius * radius - y * y)) + 1
    value.capture.sampled_points = count
    value.candidates[0].sample_refs = [[0, count]]
    return oracleAttachment(value, 2, `radius-${radius}`)
  }
  const first = dense(31)
  const firstSize = Buffer.byteLength(oracleCanonicalJson(attentionSnapshotFromAttachment(first)))
  let second = dense(1)
  let combined = 0
  for (let radius = 30; radius >= 1; radius--) {
    const candidate = dense(radius)
    const size = firstSize + Buffer.byteLength(oracleCanonicalJson(attentionSnapshotFromAttachment(candidate)))
    if (size < ATTENTION_ORACLE_LIMITS.expanded) {
      second = candidate
      combined = size
      break
    }
  }
  expect(combined).toBeGreaterThan(0)
  const v1 = attentionSnapshotFromAttachment(oracleAttachment())
  while (Buffer.byteLength(oracleCanonicalJson(v1)) <= ATTENTION_ORACLE_LIMITS.expanded - combined) {
    const candidate = structuredClone(v1.candidates[0])
    candidate.target_id = `padding-${v1.candidates.length}`
    delete candidate.action_ref
    candidate.summary!.text = 'x'.repeat(512)
    v1.candidates.push(candidate)
  }
  const plain = oracleAttachment(v1, 1, 'plain')
  expect(Buffer.byteLength(oracleCanonicalJson([first, second, plain]))).toBeLessThan(32768)
  expect(attentionSnapshotsFromAttachments([first, second])).toHaveLength(2)
  expect(() => attentionSnapshotsFromAttachments([plain, first, second])).toThrow()
  expect(() => attentionSnapshotsFromAttachments([first, second, plain])).toThrow()
})

